@st.cache_resource
def load_model():
    tfidf = joblib.load(HERE / "tfidf_vectorizer.pkl")
    model = joblib.load(HERE / "svm_model.pkl")
    # Average linear weights of the calibrated SVM folds (used only for the explanation).
    coefs = []
    for c in getattr(model, "calibrated_classifiers_", []):
        est = getattr(c, "estimator", None) or getattr(c, "base_estimator", None)
        if est is not None and hasattr(est, "coef_"):
            coefs.append(est.coef_[0])
    coef = np.mean(coefs, axis=0) if coefs else None
    return tfidf, model, coef


def clean_text(t: str) -> str:
    """Same preprocessing as in the training notebook."""
    t = str(t).lower()
    t = re.sub(r"http\S+|www\S+", " ", t)
    t = re.sub(r"[^a-z\s]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def verdict(p: float):
    if p >= 0.65:
        return "Likely AI-generated"
    if p <= 0.35:
        return "Likely human-written"
    return "Inconclusive"


def influential_terms(tfidf, vec, coef, k=5):
    contrib = vec.multiply(coef).toarray()[0]
    names = tfidf.get_feature_names_out()
    order = np.argsort(contrib)
    human = [names[i] for i in order[:k] if contrib[i] < 0]
    ai = [names[i] for i in order[::-1][:k] if contrib[i] > 0]
    return ai, human


